import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import {annualSeries,idsRows,concessionalRatio,fetchConcessionalDebt,metricRefreshStatuses} from './worldbank-debt.mjs';
const fixture=(code,value=20,year=2024)=>({pages:1,lastupdated:'2026-10-01',source:{id:'6',data:[{variable:[{concept:'Country',id:'AGO'},{concept:'Series',id:code},{concept:'Counterpart-Area',id:'WLD'},{concept:'Time',id:`YR${year}`}],value}]}});
assert.equal(annualSeries([{date:'2024',value:0},{date:'2025',value:''}],2026).length,1);
assert.throws(()=>idsRows(fixture('x'),'BEN','x','6'),/mismatch/);
assert.throws(()=>idsRows({...fixture('x'),pages:2},'AGO','x','6'),/paginated/);
assert.deepEqual(concessionalRatio([{year:2024,value:10}],[{year:2023,value:100}]),[]);
assert.equal(concessionalRatio([{year:2024,value:10}],[{year:2024,value:100}])[0].value,10);
let mode='reported';
const fetchJson=async url=>{
 if(url.includes('/sources?'))return [{pages:1},[{id:'6',name:'International Debt Statistics'}]];
 const advanced=url.includes('/series/');
 const code=url.match(/\/(?:series|indicator)\/([^/?]+)/)[1];
 if(code==='DT.DOD.ALLC.ZS' && (!advanced || mode!=='reported'))throw Error('Indicator lookup failed');
 if(mode==='failed' && advanced)throw Error('HTTP 503');
 if(advanced)return fixture(code,code==='DT.DOD.DECT.CD'?100:20);
 return [{pages:1,lastupdated:'2026-10-01'},[{date:'2024',value:12}]];
};
const opts={iso3:'AGO',sourceId:'6',currentYear:2026,fetchJson};
assert.equal((await fetchConcessionalDebt(opts)).method,'reported');
mode='calculated';const calc=await fetchConcessionalDebt(opts);assert.equal(calc.series[0].value,20);assert.equal(calc.inputSources.length,2);
mode='failed';await assert.rejects(fetchConcessionalDebt(opts),e=>e.requests.length===3);
const statuses=metricRefreshStatuses({a:{lastSuccessAt:'old'}},{a:{code:'A'},b:{code:'B'}},{b:{value:1}},{a:{status:'retrieval_failed',error:'503'}},'new');
assert.equal(statuses.a.lastSuccessAt,'old');assert.equal(statuses.b.lastSuccessAt,'new');
assert.equal(metricRefreshStatuses(null,{a:{code:'A'}},{},{},'new').a.lastSuccessAt,null);
const code=fs.readFileSync(new URL('./update-economic.mjs',import.meta.url),'utf8');
const context={console:{log(){}},fetchJson,annualSeries,fetchConcessionalDebt};vm.createContext(context);
vm.runInContext(code.slice(code.indexOf('const WB_INDICATORS'),code.indexOf('// Optional verified live'))+code.slice(code.indexOf('// Resolve the debt database'),code.indexOf('function parseCsv'))+';this.run=fetchWorldBank;',context);
mode='calculated';const result=await context.run('AGO');assert.equal(Object.keys(result.indicators).length,7);assert.equal(result.indicators.concessionalDebtPct.calculationMethod,'calculated');
mode='failed';const failed=await context.run('AGO');assert.equal(Object.keys(failed.indicators).length,6);assert.equal(failed.diagnostics.concessionalDebtPct.status,'retrieval_failed');
console.log('PASS: IDS identity, pagination, zero values, same-year calculation, reported/calculated fallbacks, failure diagnostics, per-metric timestamps and updater integration.');
